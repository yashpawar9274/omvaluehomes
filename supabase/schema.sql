create table if not exists public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.admin_users
    where user_id = (select auth.uid())
  );
$$;

revoke all on function public.is_admin() from public;
grant execute on function public.is_admin() to anon, authenticated;

create table if not exists public.content_posts (
  id bigint generated by default as identity primary key,
  title text not null,
  slug text not null unique,
  excerpt text not null default '',
  body text not null default '',
  category text not null default 'Property Updates',
  language text not null default 'English',
  image_url text not null default '',
  image_alt text not null default '',
  video_url text not null default '',
  meta_title text not null default '',
  meta_description text not null default '',
  author text not null default 'BudgetHomes Editorial',
  status text not null default 'draft' check (status in ('draft', 'published')),
  featured boolean not null default false,
  published_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.leads (
  id bigint generated by default as identity primary key,
  name text not null,
  phone text not null,
  bhk text not null default 'Not selected',
  budget text not null default 'Not specified',
  visit_date text not null default 'Flexible',
  source text not null default 'website',
  page text not null default '/',
  status text not null default 'new',
  created_at timestamptz not null default now()
);

create table if not exists public.media_assets (
  id bigint generated by default as identity primary key,
  object_key text not null unique,
  url text not null,
  file_name text not null,
  content_type text not null,
  alt_text text not null default '',
  uploaded_by text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.video_items (
  id bigint generated by default as identity primary key,
  title text not null,
  label text not null default 'Flat Tour',
  description text not null default '',
  video_url text not null,
  poster_url text not null default '',
  poster_alt text not null default '',
  orientation text not null default 'landscape'
    check (orientation in ('landscape', 'vertical')),
  status text not null default 'draft' check (status in ('draft', 'published')),
  featured boolean not null default false,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.admin_users enable row level security;
