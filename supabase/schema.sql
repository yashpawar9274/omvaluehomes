drop policy if exists "Admins upload BudgetHomes media" on storage.objects;
create policy "Admins upload BudgetHomes media"
on storage.objects for insert
to authenticated
with check (
  bucket_id = 'budgethomes-media'
  and public.is_admin()
);

drop policy if exists "Admins update BudgetHomes media" on storage.objects;
create policy "Admins update BudgetHomes media"
on storage.objects for update
to authenticated
using (
  bucket_id = 'budgethomes-media'
  and public.is_admin()
)
with check (
  bucket_id = 'budgethomes-media'
  and public.is_admin()
);

drop policy if exists "Admins delete BudgetHomes media" on storage.objects;
create policy "Admins delete BudgetHomes media"
on storage.objects for delete
to authenticated
using (
  bucket_id = 'budgethomes-media'
  and public.is_admin()
);

