alter table public.leads enable row level security;
alter table public.media_assets enable row level security;
alter table public.video_items enable row level security;

drop policy if exists "Admins can read their membership" on public.admin_users;
create policy "Admins can read their membership"
on public.admin_users for select
to authenticated
using (user_id = (select auth.uid()));

drop policy if exists "Published posts are public" on public.content_posts;
create policy "Published posts are public"
on public.content_posts for select
to anon, authenticated
using (status = 'published');

drop policy if exists "Admins manage posts" on public.content_posts;
create policy "Admins manage posts"
on public.content_posts for all
to authenticated
using (public.is_admin())
with check (public.is_admin());

drop policy if exists "Published videos are public" on public.video_items;
create policy "Published videos are public"
on public.video_items for select
to anon, authenticated
using (status = 'published');

drop policy if exists "Admins manage videos" on public.video_items;
create policy "Admins manage videos"
on public.video_items for all
to authenticated
using (public.is_admin())
with check (public.is_admin());

